// Builds the storefront's static catalog from the preserved reference extraction (read-only inputs).
// Inputs : reference/extracted/{products,settings}.json, reference/original-ui/extracted-assets/**
// Outputs: src/data/catalog.json (money in integer piasters), public/products/*, public/brand/*
// Usage  : node scripts/build-storefront-data.mjs
import fs from 'node:fs'; import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const rd = (p) => JSON.parse(fs.readFileSync(path.join(root, p), 'utf8'));
const products = rd('reference/extracted/products.json'), settings = rd('reference/extracted/settings.json'), idx = rd('reference/extracted/assets-index.json');
const P = (n) => (n == null ? null : Math.round(n * 100));
fs.mkdirSync(path.join(root, 'public/products'), { recursive: true }); fs.mkdirSync(path.join(root, 'public/brand'), { recursive: true });
const cp = (rel, destDir) => { const base = path.basename(rel); fs.copyFileSync(path.join(root, rel), path.join(root, destDir, base)); return '/' + path.basename(destDir) + '/' + base; };
if (idx.homeBot) cp(idx.homeBot, 'public/brand');
const out = {
  note: 'GENERATED by scripts/build-storefront-data.mjs from the original demo data. Prices/stock are demo values (stock=10 each) until the real DB/admin replaces them.',
  categories: [{ id: 'books', name: 'الكتب' }, { id: 'tshirts', name: 'التيشرتات' }, { id: 'notebooks', name: 'النوت بوك' }, { id: 'other', name: 'منتجات متنوعة' }],
  tiers: settings.tiers.map((t) => ({ min: P(t.min), rate: t.rate })),
  policies: Object.fromEntries(Object.entries(settings.policies).map(([k, [title, text]]) => [k, { title, text }])),
  hero: Object.entries(idx.hero).map(([id, f]) => ({ id, image: cp(f, 'public/brand') })),
  products: products.map((p) => ({
    id: p.id, category: p.category, name: p.name, description: p.description, price: P(p.price), salePrice: P(p.salePrice),
    images: p.images.map((f) => cp(f, 'public/products')), createdAt: p.createdAt,
    variants: p.variants.map((v) => ({ ...(v.size ? { size: v.size } : {}), ...(v.color ? { color: v.color } : {}), stock: v.stock, ...(v.price != null ? { price: P(v.price) } : {}) })),
  })),
};
fs.writeFileSync(path.join(root, 'src/data/catalog.json'), JSON.stringify(out) + '\n');
console.log({ products: out.products.length, bytes: fs.statSync(path.join(root, 'src/data/catalog.json')).size });
